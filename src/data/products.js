/* ------------------------------- selectors ------------------------------- */

export const getProduct = (slug) => PRODUCTS.find((x) => x.slug === slug)

export const byCategory = (slug) => PRODUCTS.filter((x) => x.category === slug)

export const bestsellers = () =>
  PRODUCTS.filter((x) => x.tags.includes('bestseller')).sort((a, b) => b.reviews - a.reviews)

export const newArrivals = () => PRODUCTS.filter((x) => x.badge === 'New' || x.tags.includes('new'))

export const onSale = () => PRODUCTS.filter((x) => x.compareAt && x.compareAt > x.price)

export const relatedTo = (product, limit = 4) =>
  PRODUCTS.filter((x) => x.category === product.category && x.id !== product.id).slice(0, limit)

export const searchProducts = (query) => {
  const q = query.trim().toLowerCase()
  if (!q) return []
  return PRODUCTS.filter((x) =>
    [x.name, x.category, x.subcategory, x.short, ...x.tags].join(' ').toLowerCase().includes(q),
  ).slice(0, 8)
}

export const priceRange = () => {
  const prices = PRODUCTS.map((x) => x.price)
  return [Math.min(...prices), Math.max(...prices)]
}
